"""
A/B test simulator.

Lets the user design a randomized experiment on the bundle pay discount and
read the result properly -- observed lift, confidence interval, significance.

IMPORTANT FRAMING: the "effect" here is generated by the same utility model
that produced the training data, so this does NOT discover anything causal
about real shoppers. What it demonstrates is experimental DESIGN and READOUT:
randomization, sample sizing, and the difference between an observed
difference and a statistically distinguishable one.
"""

import numpy as np
import pandas as pd

# Coefficients of the latent utility model (same as acceptance_model.py)
COEF = {
    "intercept": -3.10,
    "pay_per_hour": 0.140,
    "est_minutes": -0.011,
    "total_items": -0.030,
    "pay_per_km": 0.220,
    "rating_offset": -0.850,
    "preferred": 0.320,
    "both_shop": -0.280,
    "same_store": 0.150,
    "noise_sd": 1.15,
}


def _accept_prob(df, discount):
    offer = df["solo_pay_total"] * discount
    pph = offer / (df["est_minutes"] / 60)
    ppk = offer / (df["bundle_dist_km"] + 0.1)
    z = (COEF["intercept"]
         + COEF["pay_per_hour"] * pph
         + COEF["est_minutes"] * df["est_minutes"]
         + COEF["total_items"] * df["total_items"]
         + COEF["pay_per_km"] * ppk
         + COEF["rating_offset"] * (df["shopper_rating"] - 4.7)
         + COEF["preferred"] * df["preferred_shopper"]
         + COEF["both_shop"] * df["both_shop_flag"]
         + COEF["same_store"] * df["same_store_flag"])
    return 1 / (1 + np.exp(-z))


def run_experiment(offers, control_discount, treatment_discount, sample_size, seed=None):
    """Randomly assign bundles to control/treatment, simulate outcomes, analyze."""
    rng = np.random.default_rng(seed)

    n = min(sample_size, len(offers))
    idx = rng.choice(len(offers), size=n, replace=False)
    sample = offers.iloc[idx].reset_index(drop=True)

    # RANDOM assignment -- this is what makes the comparison causal within the sim
    assign = rng.random(n) < 0.5
    ctrl, trt = sample[~assign], sample[assign]

    def simulate(group, discount):
        if len(group) == 0:
            return np.array([])
        p = _accept_prob(group, discount).to_numpy()
        # add the unobservable-preference noise, then realize the outcome
        z_noise = rng.normal(0, COEF["noise_sd"], len(group))
        p_adj = 1 / (1 + np.exp(-(np.log(p / (1 - p)) + z_noise)))
        return (rng.random(len(group)) < p_adj).astype(int)

    y_ctrl = simulate(ctrl, control_discount)
    y_trt = simulate(trt, treatment_discount)

    n_c, n_t = len(y_ctrl), len(y_trt)
    p_c = y_ctrl.mean() if n_c else 0.0
    p_t = y_trt.mean() if n_t else 0.0
    lift = p_t - p_c

    # standard error of the difference in two proportions
    se = np.sqrt(p_c * (1 - p_c) / max(n_c, 1) + p_t * (1 - p_t) / max(n_t, 1))
    ci_low, ci_high = lift - 1.96 * se, lift + 1.96 * se
    z_stat = lift / se if se > 0 else 0.0
    # two-sided p-value from the normal approximation
    from math import erfc, sqrt
    p_value = erfc(abs(z_stat) / sqrt(2))

    # Economic read: pay change vs acceptance change
    avg_solo = sample["solo_pay_total"].mean()
    pay_delta = avg_solo * (treatment_discount - control_discount)

    return {
        "n_total": n,
        "n_control": n_c,
        "n_treatment": n_t,
        "control_rate": p_c,
        "treatment_rate": p_t,
        "lift": lift,
        "relative_lift": lift / p_c if p_c > 0 else 0.0,
        "ci_low": ci_low,
        "ci_high": ci_high,
        "se": se,
        "z_stat": z_stat,
        "p_value": p_value,
        "significant": p_value < 0.05,
        "extra_pay_per_bundle": pay_delta,
        "control_discount": control_discount,
        "treatment_discount": treatment_discount,
    }


def power_curve(offers, control_discount, treatment_discount, sizes, reps=12, seed=0):
    """How often does the test detect the effect, at each sample size?"""
    rows = []
    for i, s in enumerate(sizes):
        hits = 0
        for r in range(reps):
            res = run_experiment(offers, control_discount, treatment_discount,
                                 s, seed=seed + i * 100 + r)
            if res["significant"]:
                hits += 1
        rows.append({"sample_size": s, "detection_rate": hits / reps})
    return pd.DataFrame(rows)
